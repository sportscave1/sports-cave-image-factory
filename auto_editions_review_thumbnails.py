"""Optional derived review cache. Never owns preparation or approval state."""
from contextlib import contextmanager
import json
import logging
import os
from pathlib import Path
import shutil
import tempfile
import threading
import time
import uuid

import auto_editions as ae
from auto_editions_bulk_jobs import PreviewStore

LOG = logging.getLogger(__name__)
BACKGROUND = threading.BoundedSemaphore(1)


class ReviewBuildStore(PreviewStore):
    """Short transactions; no connection held during transfer or decoding."""
    def claim(self, identity):
        token = str(uuid.uuid4())
        with self.connect() as conn, conn.cursor() as cur:
            cur.execute("""INSERT INTO auto_edition_review_preview_builds(identity,token,lease_until)
                VALUES(%s,%s,now()+interval '2 minutes') ON CONFLICT(identity) DO UPDATE
                SET token=excluded.token,lease_until=excluded.lease_until,updated_at=now()
                WHERE auto_edition_review_preview_builds.lease_until<=now() RETURNING token""", (identity, token))
            return token if cur.fetchone() else None

    def renew(self, identity, token):
        with self.connect() as conn, conn.cursor() as cur:
            cur.execute("""UPDATE auto_edition_review_preview_builds SET lease_until=now()+interval '2 minutes',updated_at=now()
                WHERE identity=%s AND token=%s AND lease_until>now() RETURNING token""", (identity, token))
            return bool(cur.fetchone())

    def release(self, identity, token):
        with self.connect() as conn, conn.cursor() as cur:
            cur.execute("""UPDATE auto_edition_review_preview_builds SET lease_until=now(),updated_at=now()
                WHERE identity=%s AND token=%s""", (identity, token))

    def publish(self, identity, token, outputs):
        # The owner row serializes lease takeover and both immutable JPEG writes.
        with self.connect() as conn, conn.cursor() as cur:
            cur.execute("""SELECT token FROM auto_edition_review_preview_builds
                WHERE identity=%s AND token=%s AND lease_until>now() FOR UPDATE""", (identity, token))
            if not cur.fetchone(): return False
            for key, data in outputs.items():
                if len(data)>524288: raise ValueError('Review thumbnail exceeds bounds.')
                cur.execute("""INSERT INTO auto_edition_review_previews(identity,jpeg) VALUES(%s,decode(%s,'hex'))
                    ON CONFLICT(identity) DO UPDATE SET jpeg=excluded.jpeg WHERE auto_edition_review_previews.jpeg<>excluded.jpeg""", (key, data.hex()))
            return True


@contextmanager
def build_lease(store, identity):
    if not isinstance(store, ReviewBuildStore):
        yield None
        return
    token = store.claim(identity)
    if not token:
        yield False
        return
    stop = threading.Event()
    def heartbeat():
        while not stop.wait(20):
            try:
                if not store.renew(identity, token): return
            except Exception:
                LOG.warning('review_thumbnail_lease_renewal_deferred')
                return
    thread = threading.Thread(target=heartbeat, name='review-thumbnail-lease', daemon=True)
    thread.start()
    try: yield token
    finally:
        stop.set();thread.join(timeout=1)
        try: store.release(identity, token)
        except Exception: LOG.warning('review_thumbnail_lease_release_deferred')


def local_ready(record, root):
    """Only immutable generated bytes, never PSDs or provider/catalogue scanning."""
    from auto_editions_bulk import evidence
    m=evidence(record);root=Path(root)
    for asset in (m['master'],m['patches']['1']):
        path=ae.asset_path(root,asset)
        if path.is_symlink():raise ValueError('Local review assets must be regular files.')
    return root


def schedule_prepared(record, root, store):
    """Use the existing two-builder/eight-pending pool; keep a private file snapshot.

    Called only after the master import/checkpoint succeeded. A full pool, missing
    migration or failed thumbnail leaves normal preparation success unchanged.
    """
    from auto_editions_bulk import evidence, thumbnails, preview_builds
    evidence(record);key=thumbnails.key(record)
    with preview_builds.lock:
        for identity,(future,_) in list(preview_builds.pending.items()):
            if future.done():preview_builds.pending.pop(identity)
        # Imported-cache work never fills the queue ahead of visible requests.
        if preview_builds.pending:return False
        folder=tempfile.TemporaryDirectory(prefix='sc-review-import-')
        try:
            # Hardlinks retain the verified uploaded files after request scratch
            # cleanup without another large transfer. Workers only read them.
            for asset in (record['manifest']['master'],record['manifest']['patches']['1']):
                source=Path(root)/asset['name'];target=Path(folder.name)/asset['name']
                if source.is_symlink() or not source.is_file():raise ValueError('Missing local review assets.')
                try:os.link(source,target)
                except OSError:shutil.copyfile(source,target)
            queued_at=time.perf_counter()
            def build():
                try:
                    if not BACKGROUND.acquire(blocking=False):return None
                    try:
                        # Yield before starting if a paid render owns its budget.
                        if not ae._RENDER_LOCK.acquire(blocking=False):return None
                        ae._RENDER_LOCK.release()
                        return thumbnails.get(record,None,300,store,local_root=folder.name,background=True,queued_at=queued_at)
                    finally:BACKGROUND.release()
                except Exception:
                    LOG.warning('review_thumbnail_pregeneration_deferred preparation=%s',record['hash'],exc_info=True)
                    return None
                finally:folder.cleanup()
            future=preview_builds.pool.submit(build)
            future.add_done_callback(lambda finished:setattr(finished,'review_finished_at',time.monotonic()))
            preview_builds.pending[key[0]]=(future,time.monotonic())
            return True
        except Exception:
            folder.cleanup()
            raise


def backfill(items, store, checkpoint, *, limit=2, max_seconds=10):
    """One explicit, bounded local-assets batch. No provider fallback or auto-run.

    items is a caller-supplied list of {record, root}, at most 1000 exports.
    Failures remain pending; a persisted rotating cursor resumes fairly. One
    indivisible image decode may exceed the between-item time budget.
    """
    from auto_editions_bulk import ReviewCache,evidence
    if not isinstance(items,list) or len(items)>1000 or not 1<=limit<=8 or not 0<max_seconds<=60:
        raise ValueError('Explicit bounded thumbnail backfill required.')
    path=Path(checkpoint);state=json.loads(path.read_text()) if path.exists() else dict(cursor=0,done=[])
    cache=ReviewCache();wanted={ae.fingerprint(cache.key(item['record'])) for item in items}
    done=set(state['done'])&wanted;cursor=state['cursor']%len(items) if items else 0
    results=[];start=time.monotonic()
    if not BACKGROUND.acquire(blocking=False):return dict(results=[],pending=True)
    try:
        for offset in range(min(limit,len(items))):
            if time.monotonic()-start>=max_seconds:break
            index=(cursor+offset)%len(items);item=items[index];record=item['record'];key=ae.fingerprint(cache.key(record))
            result='Cached'
            try:
                evidence(record)
                persisted=store.get(key)
                if cache.valid(persisted,300):done.add(key)
                else:done.discard(key)
                if key not in done:
                    if not ae._RENDER_LOCK.acquire(blocking=False):break
                    ae._RENDER_LOCK.release()
                    root=local_ready(record,item['root'])
                    data=cache.get(record,None,300,store,local_root=root,background=True)
                    if data is None:result='Pending'
                    elif store.get(key)!=data:result='Pending' # Failed persistence is recoverable.
                    else:done.add(key);result='Built'
            except Exception:result='Pending'
            results.append(dict(identity=key,result=result));state['cursor']=(index+1)%len(items)
            state['done']=sorted(done)
            path.parent.mkdir(parents=True,exist_ok=True);temporary=path.with_name(path.name+'.'+uuid.uuid4().hex+'.tmp')
            temporary.write_text(json.dumps(state),encoding='utf-8');os.replace(temporary,path)
    finally:BACKGROUND.release()
    return dict(results=results,pending=bool(wanted-done))
